import sbt._
import java.util.Base64

/** Generates a Scala object holding binary files as chunked base64 strings.
  *
  * Chunks stay below the 65535-byte class-file constant limit, and the decoding uses
  * `java.util.Base64`, available on the JVM and in the Scala.js javalib.
  */
object Embed {
  private val ChunkSize = 32000

  def generate(
      outDir: File,
      pkg: String,
      objectName: String,
      files: Seq[(String, File)]
  ): Seq[File] = {
    val out = outDir / pkg.replace('.', '/') / s"$objectName.scala"
    val sb = new StringBuilder
    sb ++= s"package $pkg\n\n"
    sb ++= "// Generated by project/Embed.scala. Do not edit.\n"
    sb ++= s"object $objectName:\n"
    files.foreach { case (name, file) =>
      val b64 = Base64.getEncoder.encodeToString(IO.readBytes(file))
      val chunks = b64.grouped(ChunkSize).toSeq
      sb ++= s"  private def ${name}Parts: Array[String] = Array(\n"
      chunks.foreach(c => sb ++= "    \"" + c + "\",\n")
      sb ++= "  )\n"
      sb ++= s"  lazy val $name: Array[Byte] =\n"
      sb ++= s"    java.util.Base64.getDecoder.decode(${name}Parts.mkString)\n\n"
    }
    IO.write(out, sb.toString)
    Seq(out)
  }
}
